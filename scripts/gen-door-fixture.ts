/**
 * Writes supabase/tests/door_fixture.sql from src/lib/door-fixture.ts: one
 * assertion per run, compute_verdict() against the expected verdict, total,
 * killed_at_gate, scores and demand_capped. run.sh feeds the file to the test
 * database after the migrations; `npm test` checks the file is in step with
 * the fixture. Run: npx tsx scripts/gen-door-fixture.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { DOOR_FIXTURE } from "../src/lib/door-fixture.ts";

export const DOOR_FIXTURE_SQL_PATH = resolve(import.meta.dirname, "../supabase/tests/door_fixture.sql");

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => q(JSON.stringify(v));

export function renderDoorFixtureSql(): string {
  const rows = DOOR_FIXTURE.map((r) => {
    const input = { gates: r.input.gates.map((g) => (typeof g === "boolean" ? g : null)), scores: r.input.scores ?? null, demand_evidence: r.input.demand_evidence ?? false };
    const expect = { verdict: r.expect.verdict, total: r.expect.total, killed_at_gate: r.expect.killed_at_gate, scores: r.expect.scores, demand_capped: r.expect.demand_capped };
    return `  (${q(r.name)}, ${json(input)}::jsonb, ${json(expect)}::jsonb)`;
  });
  return `-- door_fixture.sql — GENERATED by scripts/gen-door-fixture.ts from src/lib/door-fixture.ts. Do not edit.
-- The same ${DOOR_FIXTURE.length} runs computeVerdict() (src/lib/door.ts) is tested on; compute_verdict() must agree on every one.
\\set ON_ERROR_STOP on
do $$
declare r record; got jsonb; want jsonb; mismatches text[] := '{}'; n int := 0;
begin
  for r in
    select * from (values
${rows.join(",\n")}
    ) as f(name, input, expect)
  loop
    n := n + 1;
    got := public.compute_verdict(r.input) - 'rules_version';
    want := r.expect;
    if got <> want then
      mismatches := mismatches || (r.name || ': got ' || got::text || ' want ' || want::text);
    end if;
  end loop;
  if cardinality(mismatches) > 0 then
    raise exception 'door fixture: % of % runs disagree with src/lib/door.ts: %', cardinality(mismatches), n, mismatches;
  end if;
  raise notice 'door fixture: compute_verdict() agrees with src/lib/door.ts on all % runs', n;
end $$;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  writeFileSync(DOOR_FIXTURE_SQL_PATH, renderDoorFixtureSql());
  console.log(`wrote ${DOOR_FIXTURE_SQL_PATH} (${DOOR_FIXTURE.length} runs)`);
}
